"""FORM table of the family numerators (generic: scalar products read from the family files).

    python3 isp_table.py      (run in Families/ after the family rules fams/fams<n>.inc exist)

fams<n>.inc has one rule  id <sp>*TOPO(n) = <combination of DD's of family n>;  per scalar product.
Writes fams/isp_table.inc   Table ISP(n,k) = rule k of family n  (k in the order of fams1.inc)
       fams/isp_apply.inc   id <sp_k>^n1?*TOPO(n?) = TOPO(n)*ISP(n,k)^n1; .sort   for every k (included by contractPj)
"""
import glob
import os
import re
import sys

os.chdir(os.path.dirname(os.path.abspath(__file__)))
files = sorted(glob.glob("fams/fams[0-9]*.inc"), key=lambda f: int(re.search(r"(\d+)\.inc$", f).group(1)))
rule = re.compile(r"id (\S+)\*TOPO\((\d+)\) = (.*);\s*$")
SP = [m.group(1) for m in map(rule.match, open(files[0])) if m]
lines = ["* generated by isp_table.py from fams/fams<n>.inc: ISP(n,k) = scalar product k of family n in its DD's",
         "* k = 1..%d: %s" % (len(SP), ", ".join(SP)), "Table sparse, ISP(2);"]
for f in files:
    n = int(re.search(r"(\d+)\.inc$", f).group(1))
    found = []
    for line in open(f):
        m = rule.match(line)
        if not m:
            continue
        sp, nn, rhs = m.groups()
        t = f"TOPO({n})"
        if int(nn) != n or sp not in SP:
            sys.exit(f"{f}: unexpected rule {line[:80]}")
        rhs = rhs.replace("*" + t + "*", "*").replace(t + "*", "").replace("*" + t, "")
        if "TOPO" in rhs:
            sys.exit(f"{f}: TOPO left in {line[:80]}")
        lines.append(f"Fill ISP({n},{SP.index(sp) + 1}) = {rhs};")
        found.append(sp)
    if sorted(found) != sorted(SP):
        sys.exit(f"{f}: scalar products {found} differ from {SP}")
open("fams/isp_table.inc", "w").write("\n".join(lines) + "\n")
with open("fams/isp_apply.inc", "w") as f:
    f.write("* generated by isp_table.py: one scalar product per module, all its powers at once\n")
    for k, sp in enumerate(SP, 1):
        f.write(f"id {sp}^n1?*TOPO(n?) = TOPO(n)*ISP(n,{k})^n1;\n.sort\n")
    f.write("if ( count(" + ",".join(f"{sp},1" for sp in SP) + ") != 0 )\n"
            "    exit \"contractPj: scalar product left after the family numerators\";\n")
print(f"fams/isp_table.inc, isp_apply.inc: {len(files)} families x {len(SP)} scalar products ({', '.join(SP)})")

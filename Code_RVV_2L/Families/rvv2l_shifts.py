#!/usr/bin/env python3
"""Two-loop diagrams -> family and loop-momentum shift, per diagram, with Reduze (find_diagram_shifts).

    python3 rvv2l_shifts.py [P ...]        # channels (default: all of Scripts/channels.csv) -> external/<P>.2L_shifts.inc

Needs: the FORM two-loop set of the channel (Scripts/<group>/<P>/<P>_LO/external/<P>.2.inc and its QGRAF original
<P>.2.inc.qgraf, from run_all.py's qgraf step), QGRAF ($QGRAF, default qgraf) and Reduze ($REDUZE, default reduze).
Reduze project: Families/reduze/ (config: the families PL, NPL of Hjet2L in our conventions, kinematics; crossings
generated by Reduze). Per channel: QGRAF with the Reduze style (same diagrams and momentum routing as the FORM run),
find_diagram_shifts, then an independent check of every match (after the shift every loop propagator is one of the
crossed family, t and the sector ID agree; crossings in the standard notation 1 = p1, 2 = p2, 3 = r1, PLx123 = PL
with p1 -> p2 -> r1 -> p1; Reduze's x14, x24, x124, x142 = x13, x23, x123, x132), the FORM numbering (Quark2 loops dropped) from the diagram bodies, and the output for step 01:
    if ( expression([diagN]) ); multiply replace_(k1, X1, k2, X2); multiply L2F(f); endif;
with f the family number of Families/rvv2l_families.txt. Stops on any mismatch.
"""
import csv
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CODE = os.path.dirname(HERE)
SCRIPTS = os.path.join(CODE, "Scripts")
RED = os.path.join(HERE, "reduze")
QGRAF = os.environ.get("QGRAF", "qgraf")
REDUZE = os.environ.get("REDUZE", "reduze")

B = ["k1", "k2", "p1", "p2", "r1"]                     # q = -p1-p2-r1
LEG = {1: "p1", 2: "p2", 3: "q", 4: "r1"}
BASE = {"PL": ["k1", "k2", "k1-k2", "k1+p1", "k2+p1", "k1+p1+p2", "k2+p1+p2", "k1+p1+p2+r1", "k2+p1+p2+r1"],
        "NPL": ["k1", "k2", "k1+p1", "k2+p1", "k1-r1", "k2-r1", "k1-p2-r1", "k1-k2", "k1-k2-p2"]}
# crossings of the massless legs in the standard notation 1 = p1, 2 = p2, 3 = r1 (x123: p1 -> p2 -> r1 -> p1), as in
# Hjet2L; Reduze numbers the legs 1 = p1, 2 = p2, 3 = q, 4 = r1 and calls them x12, x14, x24, x124, x142
CROSS = ["", "x12", "x13", "x23", "x123", "x132"]
REDUZE_CROSS = {"": "", "x12": "x12", "x14": "x13", "x24": "x23", "x124": "x123", "x142": "x132"}
FAMILIES = [b + c for b in ("PL", "NPL") for c in CROSS]           # family number = position + 1


def from_reduze(name):
    m = re.fullmatch(r"(PL|NPL)(x\d+)?", name)
    return m.group(1) + REDUZE_CROSS[m.group(2) or ""]


def vec(s):
    s = s.replace(" ", "").replace("-", "+-")
    v = [0] * 5
    for t in filter(None, s.split("+")):
        sg = -1 if t.startswith("-") else 1
        t = t.lstrip("-")
        if t == "q":
            for i in (2, 3, 4):
                v[i] -= sg
        else:
            v[B.index(t)] += sg
    return tuple(v)


def norm(v):
    for x in v:
        if x:
            return v if x > 0 else tuple(-y for y in v)
    return v


def subst(v, X1, X2):
    out = [0, 0] + list(v[2:])
    for c, X in ((v[0], X1), (v[1], X2)):
        out = [a + c * b for a, b in zip(out, X)]
    return tuple(out)


def crossed_props(name):
    """propagator momenta (strings) of a crossed family: PLx123 = PL with p1 -> p2 -> r1 -> p1"""
    m = re.fullmatch(r"(PL|NPL)(?:x(\d+))?", name)
    perm = {i: i for i in LEG}
    if m.group(2):
        c = [4 if int(x) == 3 else int(x) for x in m.group(2)]       # label 3 = r1 = leg 4 of LEG
        for a, b in zip(c, c[1:] + c[:1]):
            perm[a] = b
    inv = {l: k for k, l in LEG.items()}
    return [re.sub(r"p1|p2|r1", lambda mm: LEG[perm[inv[mm.group(0)]]], P) for P in BASE[m.group(1)]]


def channels(sel):
    rows = list(csv.DictReader(open(os.path.join(SCRIPTS, "channels.csv"))))
    return [(r["group"], r["name"]) for r in rows if not sel or r["name"] in sel]


def bodies(path):
    t = open(path).read()
    return {int(m.group(1)): re.sub(r"\s+", "", m.group(2)) for m in re.finditer(r"id diag(\d+) = (.*?);", t, re.S)}


def run_channel(group, P):
    lo = os.path.join(SCRIPTS, group, P, f"{P}_LO")
    ext = os.path.join(lo, "external")
    if not os.path.isfile(os.path.join(ext, f"{P}.2.inc.qgraf")):
        sys.exit(f"{P}: run the qgraf step first (external/{P}.2.inc and .qgraf missing)")
    # QGRAF, Reduze style, with the channel's own card
    card = open(os.path.join(lo, "qgraf", "loop", "qgraf.dat")).read()
    card = re.sub(r"output = '[^']*' ;", f"output = '{P}.2.yaml' ;", card)
    card = re.sub(r"style = '[^']*' ;", "style = 'reduze.sty' ;", card)
    card = re.sub(r"model = '[^']*';", "model = 'model_file';", card)
    qd = os.path.join(RED, "qgraf", P)
    shutil.rmtree(qd, ignore_errors=True)
    os.makedirs(qd)
    for f in ("reduze.sty",):
        shutil.copy(os.path.join(RED, "qgraf", f), qd)
    shutil.copy(os.path.join(CODE, "QGRAF", "model_file"), qd)
    open(os.path.join(qd, "qgraf.dat"), "w").write(card)
    subprocess.run([QGRAF], cwd=qd, check=True, stdout=subprocess.DEVNULL)
    job = os.path.join(RED, "jobs", f"match_{P}.yaml")
    res = os.path.join(RED, "results", f"{P}.2.match.inc")
    os.makedirs(os.path.dirname(job), exist_ok=True)
    os.makedirs(os.path.dirname(res), exist_ok=True)
    for f in (res, res.replace(".inc", ".yaml")):
        if os.path.exists(f):
            os.remove(f)
    open(job, "w").write(f'jobs:\n  - find_diagram_shifts:\n      qgraf_file: "qgraf/{P}/{P}.2.yaml"\n'
                         f'      output_file: "results/{P}.2.match.yaml"\n      info_file_form: "results/{P}.2.match.inc"\n')
    subprocess.run([REDUZE, job], cwd=RED, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    # check every match
    txt = open(os.path.join(qd, f"{P}.2.yaml")).read()
    loops = {}
    for blk in txt.split("\ndiagram:")[1:]:
        n = int(re.search(r"name: (\d+)", blk).group(1))
        props = re.search(r"propagators:(.*?)vertices:", blk, re.S).group(1)
        loops[n] = {norm(vec(m.group(1))) for m in re.finditer(r"\[\[\w+, 3, [-+]1, ([^,]+), [^,]+, \d+\]", props)
                    if "k1" in m.group(1) or "k2" in m.group(1)}
    info = re.findall(r"DiaMatch\((\d+)\) = Sector\((\w+), (\d+), (\d+)\) \* Shift\(k1, ([^,]+), \[\], k2, ([^,]+), \[\]\)",
                      open(res).read())
    match = {}
    for n, fam, t, sid, x1, x2 in info:
        fam = from_reduze(fam)
        props = [norm(vec(p)) for p in crossed_props(fam)]
        shifted = {norm(subst(v, vec(x1), vec(x2))) for v in loops[int(n)]}
        ids = sum(1 << props.index(v) for v in shifted if v in props)
        if fam not in FAMILIES or not (shifted <= set(props) and len(shifted) == int(t) and ids == int(sid)):
            sys.exit(f"{P}: Reduze match of QGRAF diagram {n} ({fam}) fails the check")
        match[int(n)] = (fam, x1.replace(" ", ""), x2.replace(" ", ""))
    if set(match) != set(loops):
        sys.exit(f"{P}: diagrams without a match: {sorted(set(loops) - set(match))[:10]}")
    # FORM numbering (Quark2 loops dropped, renumbered) <- QGRAF numbering, from the diagram bodies
    orig, kept = bodies(os.path.join(ext, f"{P}.2.inc.qgraf")), bodies(os.path.join(ext, f"{P}.2.inc"))
    if len(orig) != len(loops):
        sys.exit(f"{P}: {len(orig)} QGRAF diagrams in the FORM set, {len(loops)} in the Reduze set")
    inv = {}
    for n, b in orig.items():
        inv.setdefault(b, []).append(n)
    lines, used = [], {}
    for new, b in sorted(kept.items()):
        if len(inv.get(b, [])) != 1:
            sys.exit(f"{P}: FORM diagram {new} not found once in the QGRAF output")
        fam, x1, x2 = match[inv[b][0]]
        f = FAMILIES.index(fam) + 1
        used[fam] = used.get(fam, 0) + 1
        lines.append(f"if ( expression([diag{new}]) );\n  multiply replace_(k1, {x1}, k2, {x2});\n"
                     f"  multiply L2F({f});\nendif;")
    out = os.path.join(ext, f"{P}.2L_shifts.inc")
    with open(out, "w") as fo:
        fo.write(f"* generated by Families/rvv2l_shifts.py: two-loop diagram -> loop-momentum shift (Reduze\n"
                 f"* find_diagram_shifts, checked) and family L2F(f) (Families/rvv2l_families.txt); FORM numbering\n")
        fo.write("\n".join(lines) + "\n")
    print(f"{P}: {len(kept)} diagrams -> " + ", ".join(f"{k} {v}" for k, v in sorted(used.items())))


def write_family_list():
    with open(os.path.join(HERE, "rvv2l_families.txt"), "w") as f:
        f.write("# RVV 2L x tree families (rvv2l_shifts.py): number, name, propagators (all legs incoming,\n"
                "# q = -p1-p2-r1). PL, NPL = Hjet2L (Code/Scripts/Templates/common.py) with p_i -> -p_i, p3 -> r1;\n"
                "# crossings in the standard notation 1 = p1, 2 = p2, 3 = r1: PLx123 = PL with p1 -> p2 -> r1 -> p1\n")
        for i, fam in enumerate(FAMILIES, 1):
            f.write(f"{i:2d}  {fam:8s}  {', '.join(crossed_props(fam))}\n")


def main(argv):
    write_family_list()
    if not os.path.isdir(os.path.join(RED, "sectormappings")):     # once: sector mappings and crossings of PL, NPL
        subprocess.run([REDUZE, os.path.join("jobs", "setup.yaml")], cwd=RED, check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    for group, P in channels(argv):
        run_channel(group, P)


if __name__ == "__main__":
    main(sys.argv[1:])

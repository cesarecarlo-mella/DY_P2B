#!/usr/bin/env python3
"""RVV 2L x tree: step-05 tables for the 12 two-loop families (PL, NPL and crossings, Families/rvv2l_shifts.py).

    python3 rvv2l_families.py       # -> fams/l2_dens.inc, l2_isp_table.inc, l2_isp_apply.inc, l2_reconstruct.inc,
                                    #    integralfamilies_r.rvv2l.m, rvv2l_props.txt

Every term of step 05 carries the family tag L2F(f) of its two-loop diagram (step 01: the diagram was shifted onto
family f), so no matching is needed here:
- global numbering: D1..D3 cuts (as RV), D4.. = the distinct loop propagators of the 12 families, written as FORM has
  them after the kinematics (q eliminated, overall sign such that the first of k1, k2, p1, p2, r1 has coefficient +1);
- the 9 loop scalar products k1.k1, k2.k2, k1.k2, k1.p1, k1.p2, k1.r1, k2.p1, k2.p2, k2.r1 of family f in its 9
  propagators (exact inversion), constants with p1.p2 = s12/2 = m2/(2 z) and p1.r1, p2.r1 left for isp_apply.inc;
- INT(topo<f>, 1,1,1, n1..n9): the 9 propagators in the order of the family (Hjet2L order); topo<f> = family number f
  (1 PL, 2 PLx12, 3 PLx13, 4 PLx23, 5 PLx123, 6 PLx132, 7 NPL, ..., 12 NPLx132).
"""
import os
import sys
from fractions import Fraction as F

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rvv2l_shifts as R                               # noqa: E402  FAMILIES, crossed_props, vec, norm

FAMS = os.path.join(HERE, "fams")
HEAD = "* generated by Families/rvv2l_families.py (RVV 2L x tree: cuts D1..D3, loop propagators D4.., families topo1..12)\n"
V = ["k1", "k2", "p1", "p2", "r1"]
SP = ["k1.k1", "k2.k2", "k1.k2", "k1.p1", "k1.p2", "k1.r1", "k2.p1", "k2.p2", "k2.r1"]
CONST = ["p1.p2", "p1.r1", "p2.r1"]


def mom_str(v):
    t = "".join(("+" if c > 0 else "-") + (f"{abs(c)}*" if abs(c) != 1 else "") + x for c, x in zip(v, V) if c)
    return t[1:] if t.startswith("+") else t


def square(v):
    """(sum a_i v_i)^2 -> (coefficients of the 9 loop scalar products, of the 3 constants)"""
    sp, cs = [F(0)] * 9, [F(0)] * 3
    for i in range(5):
        for j in range(i, 5):
            c = v[i] * v[j] * (1 if i == j else 2)
            if not c:
                continue
            name = f"{V[i]}.{V[j]}"
            if name in SP:
                sp[SP.index(name)] += c
            elif name in CONST:
                cs[CONST.index(name)] += c
            elif i == j and V[i] in ("p1", "p2", "r1"):
                pass                                    # massless legs
            else:
                sys.exit(f"unexpected scalar product {name}")
    return sp, cs


def invert(M):
    n = len(M)
    A = [row[:] + [F(int(i == j)) for j in range(n)] for i, row in enumerate(M)]
    for c in range(n):
        p = next((r for r in range(c, n) if A[r][c] != 0), None)
        if p is None:
            sys.exit("singular: the 9 propagators are not a basis of the loop scalar products")
        A[c], A[p] = A[p], A[c]
        piv = A[c][c]
        A[c] = [x / piv for x in A[c]]
        for r in range(n):
            if r != c and A[r][c] != 0:
                f = A[r][c]
                A[r] = [x - f * y for x, y in zip(A[r], A[c])]
    return [row[n:] for row in A]


def lincomb(terms):
    """[(coefficient, symbol)] -> FORM text"""
    out = ""
    for c, s in terms:
        if c == 0:
            continue
        sign = "-" if c < 0 else "+"
        a = abs(c)
        num = "" if a == 1 else (f"{a.numerator}/{a.denominator}*" if a.denominator != 1 else f"{a.numerator}*")
        out += f"{sign}{num}{s}"
    out = out.lstrip("+")
    return out or "0"


def main():
    R.write_family_list()
    fams = [(f, [R.norm(R.vec(p)) for p in R.crossed_props(f)]) for f in R.FAMILIES]
    glob_props = []
    for _, ps in fams:
        for p in ps:
            if p not in glob_props:
                glob_props.append(p)
    dnum = {p: 4 + i for i, p in enumerate(glob_props)}
    os.makedirs(FAMS, exist_ok=True)
    with open(os.path.join(FAMS, "l2_dens.inc"), "w") as f:
        f.write(HEAD + "* loop propagators of the 12 families -> D4..; the cut propagators D1..D3 are in dens.inc\n")
        f.write(f'#define L2DMAX "{3 + len(glob_props)}"\n')
        f.write("".join(f"id Prop({mom_str(p)}) = 1/D{dnum[p]};\n" for p in glob_props))
    with open(os.path.join(HERE, "rvv2l_props.txt"), "w") as f:
        f.write("# RVV 2L x tree (rvv2l_families.py): global numbering of the loop propagators (D1..D3 = cuts, as RV)\n")
        f.write("".join(f"D{dnum[p]:<3d} ({mom_str(p)})^2\n" for p in glob_props))
        f.write("\n# families: number, name, propagators in INT order (D numbers)\n")
        f.write("".join(f"topo{i:<3d} {n:8s} D[1, 2, 3, {', '.join(str(dnum[p]) for p in ps)}]\n"
                        for i, (n, ps) in enumerate(fams, 1)))
    # numerators
    tab = [HEAD, "* L2ISP(f, j): j = 1..9 -> k1.k1, k2.k2, k1.k2, k1.p1, k1.p2, k1.r1, k2.p1, k2.p2, k2.r1 of family f\n"
           "* in its DD's; p1.p2 = m2/(2 z), p1.r1 and p2.r1 are left for fams/isp_apply.inc\n", "Table sparse, L2ISP(2);\n"]
    for fi, (name, ps) in enumerate(fams, 1):
        rows = [square(p) for p in ps]
        Minv = invert([r[0] for r in rows])
        # check: Minv * M = 1
        M = [r[0] for r in rows]
        for i in range(9):
            for j in range(9):
                if sum(Minv[i][k] * M[k][j] for k in range(9)) != (1 if i == j else 0):
                    sys.exit(f"{name}: inversion check failed")
        for j in range(9):
            terms = [(Minv[j][i], f"DD{dnum[ps[i]]}") for i in range(9)]
            const = [F(0)] * 3
            for i in range(9):
                for c in range(3):
                    const[c] -= Minv[j][i] * rows[i][1][c]
            terms += [(const[0] / 2, "m2*Den(z)"), (const[1], "p1.r1"), (const[2], "p2.r1")]
            tab.append(f"Fill L2ISP({fi},{j + 1}) = {lincomb(terms)};\n")
    open(os.path.join(FAMS, "l2_isp_table.inc"), "w").write("".join(tab))
    with open(os.path.join(FAMS, "l2_isp_apply.inc"), "w") as f:
        f.write(HEAD + "* loop scalar products of family L2F(f) (one per module), then TOPO(1) for p1.r1, p2.r1 (isp_apply.inc)\n")
        for j, s in enumerate(SP, 1):
            f.write(f"id {s}^n1?*L2F(n?) = L2F(n)*L2ISP(n,{j})^n1;\n.sort\n")
        f.write(f"if ( count({','.join(s + ',1' for s in SP)}) != 0 ) exit \"contractPj: loop scalar product left\";\n")
        f.write("multiply TOPO(1);\n.sort\n")
    with open(os.path.join(FAMS, "l2_reconstruct.inc"), "w") as f:
        f.write(HEAD)
        for fi, (name, ps) in enumerate(fams, 1):
            pat = "".join(f"/DD{dnum[p]}^n{i}?" for i, p in enumerate(ps, 1))
            f.write(f"* topo{fi} = {name}\nid L2F({fi})*TOPO(1)/DD1/DD2/DD3{pat} = "
                    f"INT(topo{fi},1,1,1,{','.join(f'n{i}' for i in range(1, 10))});\n")
    with open(os.path.join(HERE, "integralfamilies_r.rvv2l.m"), "w") as f:
        f.write("(* generated by Families/rvv2l_families.py. {families, names, definitions}: entry N = topoN, its 12\n"
                "   propagators in the global numbering DD[..] of the FORM code (INT(topoN, n1, ..., n12)); names as in\n"
                "   Hjet2L with the crossings of p1, p2, r1 (1, 2, 3). Momenta as in FORM: p1, p2, r1, k1, k2 incoming,\n"
                "   q = -p1-p2-r1; Den[k] = 1/k^2, Den[k, m2] = 1/(k^2 - m2), DD[3] = 1/(-q.p1 + u q.p2). *)\n{\n{\n")
        f.write(",\n".join(" {" + ", ".join(["DD[1]", "DD[2]", "DD[3]"] + [f"DD[{dnum[p]}]" for p in ps]) + "}"
                           for _, ps in fams) + "\n},\n{" + ", ".join(f'"{n}"' for n, _ in fams) + "},\n{\n")
        defs = [" DD[1] -> Den[r1]", " DD[2] -> Den[p1+p2+r1, m2]", " DD[3] -> Den[-sp[q, p1] + u*sp[q, p2]]"]
        defs += [f" DD[{dnum[p]}] -> Den[{mom_str(p)}]" for p in glob_props]
        f.write(",\n".join(defs) + "\n}\n}\n")
    print(f"{len(fams)} families, {len(glob_props)} distinct loop propagators (D4..D{3 + len(glob_props)}) -> "
          "fams/l2_*.inc, rvv2l_props.txt, integralfamilies_r.rvv2l.m")


if __name__ == "__main__":
    main()

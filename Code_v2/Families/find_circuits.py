#!/usr/bin/env python3
"""Candidate partial-fraction identities: minimal linearly dependent sets of propagators.

  python3 find_circuits.py        (needs propagators/all.m from collect_props.py)

A set T of regular propagators is a candidate if, on the cut (DD1..DD5 = 0), its propagators satisfy one linear
relation  sum_i c_i D_i = const  that involves all of them, and no smaller subset of T satisfies one (T is minimal).
Only subsets of the sets in allMaxProducts are tested, i.e. propagator sets that occur in some channel.
The test is numerical (two generic values of u); pf_identities.wl redoes every relation exactly.

Writes  circuits.m   {{i, j, ...}, ...}  (DD numbers, see denoms.m)
"""
import itertools, os, re, sys
from fractions import Fraction

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import collect_props as cp

# regular propagators DD6..DD29, same numbering as n3lo/RRR/Families_Identification (DD6..DD23) + DD24..DD29
REGULAR = ["p1+r1", "p2+r1", "p1+r2", "p2+r2", "p1+r3", "p2+r3", "r1+r2", "r2+r3", "r1+r3",
           "p1+r1+r2", "p2+r1+r2", "p1+r1+r3", "p2+r1+r3", "p1+r2+r3", "p2+r2+r3", "r1+r2+r3",
           "p1+r1+r2+r3", "p2+r1+r2+r3",
           "p1+p2+r1", "p1+p2+r2", "p1+p2+r3", "p1+p2+r1+r2", "p1+p2+r1+r3", "p1+p2+r2+r3"]
DD = {cp.momentum(m): 6 + i for i, m in enumerate(REGULAR)}


def linear_part(vec):
    """k^2 in the variables p1.ri, p2.ri, ri.rj (i<j); ri^2 = pi^2 = 0, constants dropped."""
    a, b, c = vec[0], vec[1], vec[2:]
    return ([2 * a * x for x in c] + [2 * b * x for x in c]
            + [2 * c[i] * c[j] for i, j in ((0, 1), (0, 2), (1, 2))])


def rank(rows):
    m = [[Fraction(x) for x in r] for r in rows]
    r = 0
    for col in range(len(m[0]) if m else 0):
        piv = next((i for i in range(r, len(m)) if m[i][col] != 0), None)
        if piv is None:
            continue
        m[r], m[piv] = m[piv], m[r]
        for i in range(len(m)):
            if i != r and m[i][col] != 0:
                f = m[i][col] / m[r][col]
                m[i] = [x - f * y for x, y in zip(m[i], m[r])]
        r += 1
    return r


def make_rank(u):
    # cut relations: (p1+p2+r1+r2+r3)^2 - m2 = 0 and -q.p1 + u q.p2 = 0, linear parts
    cuts = [linear_part((1, 1, 1, 1, 1)), [1, 1, 1, -u, -u, -u, 0, 0, 0]]
    rc = rank(cuts)
    cache = {}

    def r(subset):
        key = tuple(sorted(subset))
        if key not in cache:
            cache[key] = rank([LIN[i] for i in key] + cuts) - rc
        return cache[key]
    return r


LIN = {n: linear_part(v) for v, n in DD.items()}


def main():
    text = open(os.path.join(HERE, "propagators", "all.m")).read()
    body = re.search(r"allMaxProducts = \{(.*?)\};\n", text, re.S).group(1)
    sets = [tuple(sorted(DD[cp.momentum(m)] for m in x.split(", "))) for x in re.findall(r"\{([^{}]*)\}", body)]
    subsets = {t for s in sets for k in range(2, len(s) + 1) for t in itertools.combinations(s, k)}
    found = None
    for u in (Fraction(7, 3), Fraction(-11, 5)):
        r = make_rank(u)
        circ = {t for t in subsets
                if r(t) < len(t) and all(r(t[:i] + t[i + 1:]) == len(t) - 1 for i in range(len(t)))}
        found = circ if found is None else found & circ
    found = sorted(found, key=lambda t: (len(t), t))
    with open(os.path.join(HERE, "circuits.m"), "w") as f:
        f.write("(* minimal dependent propagator sets (DD numbers), generated by find_circuits.py *)\n{\n  "
                + ",\n  ".join("{" + ", ".join(map(str, t)) + "}" for t in found) + "\n}\n")
    from collections import Counter
    print(f"{len(sets)} sets, {len(subsets)} distinct subsets tested, {len(found)} minimal dependent sets "
          f"by size: {dict(sorted(Counter(map(len, found)).items()))}  ->  circuits.m")


if __name__ == "__main__":
    main()

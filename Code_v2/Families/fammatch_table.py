"""FORM tables for the family matching: fams/fammatch_table.inc from fams/fammatch.inc (family_rules.wl).

    python3 fammatch_table.py      (run in Code_v2/Families after family_rules.wl)

fammatch.inc lists every subset of the regular propagators D6..D29 of every family once (the first family that
has it), largest sets first, as  id D6^n6?{..}*D7^n7?{..}*... = TOPO(n)*DD6^n6*...;  so the first rule that
matches a term is the one for exactly its set of propagators. The tables  FAM<m>(k1,...,km) = n  (m = size of
the set, k1 < ... < km) give the same family by a direct lookup of the sorted set of the term's D's
(contractPj: SIG(k1,...,km) -> TOPO(FAM<m>(k1,...,km))), instead of trying the rules one by one.
"""
import os
import re

os.chdir(os.path.dirname(os.path.abspath(__file__)))
fam = {}
for line in open("fams/fammatch.inc"):
    m = re.match(r"id (.*) = TOPO\((\d+)\)\*", line)
    if not m:
        continue
    ks = tuple(sorted(int(k) for k in re.findall(r"\bD(\d+)\^n\d+\?", m.group(1))))
    assert ks not in fam, ("set listed twice", ks)
    fam[ks] = int(m.group(2))
sizes = sorted({len(ks) for ks in fam})
lines = ["* generated by fammatch_table.py from fams/fammatch.inc: FAM<m>(k1,...,km) = family of the set {D_k1,...,D_km}"]
lines += [f"Table sparse, FAM{m}({m});" for m in range(1, 8)]
for ks, n in sorted(fam.items(), key=lambda x: (len(x[0]), x[0])):
    lines.append(f"Fill FAM{len(ks)}({','.join(map(str, ks))}) = {n};")
with open("fams/fammatch_table.inc", "w") as out:
    out.write("\n".join(lines) + "\n")
print(f"fams/fammatch_table.inc: {len(fam)} propagator sets (sizes {sizes[0]}..{sizes[-1]}), "
      f"{len(set(fam.values()))} families")

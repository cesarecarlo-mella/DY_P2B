"""FORM table of the family numerators: fams/isp_table.inc from fams/fams<n>.inc (family_rules.wl).

    python3 isp_table.py      (run in Code_RRR/Families after family_rules.wl)

fams<n>.inc has 9 rules  id <sp>*TOPO(n) = <combination of DD's of family n>;  for the 9 scalar products below.
The table  ISP(n, k) = <rule k of family n>  lets contractPj look up the family of a term directly
(id <sp_k>*TOPO(n?) = TOPO(n)*ISP(n,k)) instead of running every term through all the fams<n>.inc files.
"""
import glob
import os
import re

SP = ["r1.r2", "r1.r3", "r2.r3", "p1.r1", "p2.r1", "p1.r2", "p2.r2", "p1.r3", "p2.r3"]

os.chdir(os.path.dirname(os.path.abspath(__file__)))
files = sorted(glob.glob("fams/fams[0-9]*.inc"), key=lambda f: int(re.search(r"(\d+)\.inc$", f).group(1)))
lines = ["* generated by isp_table.py from fams/fams<n>.inc: ISP(n,k) = scalar product k of family n in its DD's",
         "* k = 1..9: " + ", ".join(SP),
         "Table sparse, ISP(2);"]
for f in files:
    n = int(re.search(r"(\d+)\.inc$", f).group(1))
    found = set()
    for line in open(f):
        m = re.match(r"id (\S+)\*TOPO\((\d+)\) = (.*);\s*$", line)
        if not m:
            continue
        sp, nn, rhs = m.groups()
        assert int(nn) == n and sp in SP, (f, line[:80])
        t = f"TOPO({n})"
        rhs = rhs.replace("*" + t + "*", "*").replace(t + "*", "").replace("*" + t, "")
        assert "TOPO" not in rhs, (f, line[:80])
        lines.append(f"Fill ISP({n},{SP.index(sp) + 1}) = {rhs};")
        found.add(sp)
    assert found == set(SP), (f, set(SP) - found)
with open("fams/isp_table.inc", "w") as out:
    out.write("\n".join(lines) + "\n")
print(f"fams/isp_table.inc: {len(files)} families x {len(SP)} scalar products")

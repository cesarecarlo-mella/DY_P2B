#!/usr/bin/env python3
"""RVV 1L x 1L families and step-05 tables, from the RV (one-loop box) tables of this folder (rv_families.py).

    python3 rvv_families.py          # -> fams/rvv_*.inc, rvv_families.txt, integralfamilies_r.rvv.m, rvv_topsectors.m

The amplitude loop k1 and the conjugate loop k2 are matched separately with the RV tables (fams/rv_loopcodes.inc,
rv_match_table.inc, rv_shifts.inc): k1 -> box family A (RV topoA) and its shift, k2 -> box family B and its shift
(the same tables with k1 -> k2). Global numbering: D1..D3 cuts, D4..D11 = (k1 + S)^2 (as RV), D12..D19 = (k2 + S)^2
(D(k+8) = D(k) with k1 -> k2), D20 = (k1 + k2)^2 (irreducible numerator, k1.k2 = (D20 - k1.k1 - k2.k2)/2).
Family topoN, N = 3 (A - 1) + B: propagators D1, D2, D3, the 4 box props of A in k1, the 4 box props of B in k2,
D20; INT(topoN, 1,1,1, n1..n4, m1..m4, n9) (the Reduze families rvvAB of the 1L x 1L test). No symmetries between
families or loops: the conjugation acts on the k2 factor (notes_Larin/oneloop_squared.tex).
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
FAMS = os.path.join(HERE, "fams")
HEAD = "* generated by Families/rvv_families.py (RVV 1L x 1L: cuts D1..D3, k1 D4..D11, k2 D12..D19, (k1+k2)^2 D20)\n"
SHIFT2 = 8                                          # D(k) -> D(k + 8) for k = 4..11


def k1_to_k2(s):
    return re.sub(r"\bk1\b", "k2", s)


def dd_to_k2(s):
    return re.sub(r"\b(D|DD)(\d+)\b", lambda m: m.group(1) + str(int(m.group(2)) + SHIFT2)
                  if 4 <= int(m.group(2)) <= 11 else m.group(0), s)


def rv_lines(name):
    return [l for l in open(os.path.join(FAMS, name)).read().splitlines() if l and not l.startswith("*")]


def main():
    # RV families: box props (DD numbers) per family, from rv_reconstruct.inc
    box = {}
    for line in rv_lines("rv_reconstruct.inc"):
        m = re.match(r"id RVT\((\d+)\)\*TOPO\(1\)/DD1/DD2/DD3/(.*) = INT", line)
        box[int(m.group(1))] = [int(x) for x in re.findall(r"DD(\d+)\^", m.group(2))]
    mom = {}                                         # D4..D11 momenta, from rv_loopdens.inc
    for line in rv_lines("rv_loopdens.inc"):
        m = re.match(r"id Prop\((.*)\) = 1/D(\d+);", line)
        mom[int(m.group(2))] = m.group(1)
    fams = [(a, b) for a in sorted(box) for b in sorted(box)]

    # loop codes: k1 -> PropSet (as RV), k2 -> PropSet2
    codes = rv_lines("rv_loopcodes.inc")
    with open(os.path.join(FAMS, "rvv_loopcodes.inc"), "w") as f:
        f.write(HEAD + "* loop propagators -> codes: k1 in PropSet, k2 in PropSet2 (codes and tables of rv_loopcodes.inc)\n")
        f.write("\n".join(codes) + "\n")
        f.write("\n".join(k1_to_k2(l).replace("PropSet(", "PropSet2(") for l in codes) + "\n")
    # k2 shifts
    with open(os.path.join(FAMS, "rvv_shifts2.inc"), "w") as f:
        f.write(HEAD + "* k2 -> s*k2 + s*c of the matched family (rv_shifts.inc with k1 -> k2)\n")
        f.write("\n".join(k1_to_k2(l) for l in rv_lines("rv_shifts.inc")) + "\n")
    # k2 propagators D12..D19
    with open(os.path.join(FAMS, "rvv_loopdens2.inc"), "w") as f:
        f.write(HEAD + "\n".join(dd_to_k2(k1_to_k2(l)) for l in rv_lines("rv_loopdens.inc")) + "\n")
    # k2 loop scalar products LISP2 (rv_isp_table.inc with k1 -> k2, DD4..11 -> DD12..19)
    with open(os.path.join(FAMS, "rvv_isp_table2.inc"), "w") as f:
        f.write(HEAD + "* LISP2(f, j): j = 1..4 -> k2.k2, k2.p1, k2.p2, k2.r1 of box family f in DD12..DD19\n")
        f.write("\n".join(dd_to_k2(k1_to_k2(l)).replace("LISP(", "LISP2(") for l in rv_lines("rv_isp_table.inc")) + "\n")
    # ISP: k1.k2 first, then the k1 and k2 scalar products, then TOPO(1) for p1.r1, p2.r1
    sp = ["k1.k1", "k1.p1", "k1.p2", "k1.r1"]
    with open(os.path.join(FAMS, "rvv_isp_apply.inc"), "w") as f:
        f.write(HEAD + "* k1.k2 -> (DD20 - k1.k1 - k2.k2)/2; k1.x by LISP of the k1 family (RVTA), k2.x by LISP2 of the\n"
                "* k2 family (RVTB); then TOPO(1) for p1.r1, p2.r1 (fams/isp_apply.inc)\n")
        f.write("id k1.k2^n1? = (1/2*DD20 - 1/2*k1.k1 - 1/2*k2.k2)^n1;\n.sort\n")
        for j, x in enumerate(sp, 1):
            f.write(f"id {x}^n1?*RVTA(n?) = RVTA(n)*LISP(n,{j})^n1;\n.sort\n")
        for j, x in enumerate(sp, 1):
            f.write(f"id {k1_to_k2(x)}^n1?*RVTB(n?) = RVTB(n)*LISP2(n,{j})^n1;\n.sort\n")
        left = ",".join(f"{x},1" for x in ["k1.k2"] + sp + [k1_to_k2(x) for x in sp])
        f.write(f"if ( count({left}) != 0 ) exit \"contractPj: loop scalar product left\";\n")
        f.write("multiply TOPO(1);\n.sort\n")
    # reconstruct
    with open(os.path.join(FAMS, "rvv_reconstruct.inc"), "w") as f:
        f.write(HEAD)
        for n, (a, b) in enumerate(fams, 1):
            props = [f"DD{d}" for d in box[a]] + [f"DD{d + SHIFT2}" for d in box[b]] + ["DD20"]
            pat = "".join(f"/{p}^n{i}?" for i, p in enumerate(props, 1))
            f.write(f"id RVTA({a})*RVTB({b})*TOPO(1)/DD1/DD2/DD3{pat} = "
                    f"INT(topo{n},1,1,1,{','.join(f'n{i}' for i in range(1, 10))});\n")
    # human-readable list and Mathematica export
    momk = {**{d: mom[d] for d in mom}, **{d + SHIFT2: k1_to_k2(mom[d]) for d in mom}, 20: "k1+k2"}
    with open(os.path.join(HERE, "rvv_families.txt"), "w") as f:
        f.write("# RVV 1L x 1L families (rvv_families.py): number, k1 box (RV topoA), k2 box (RV topoB), propagators D1..D12\n")
        for n, (a, b) in enumerate(fams, 1):
            dl = [1, 2, 3] + box[a] + [d + SHIFT2 for d in box[b]] + [20]
            f.write(f"topo{n:<3d} k1: RV topo{a}  k2: RV topo{b}  D{dl}\n")
    with open(os.path.join(HERE, "integralfamilies_r.rvv.m"), "w") as f:
        f.write("(* generated by Families/rvv_families.py. {families, definitions}: entry N of families = topoN, its 12\n"
                "   propagators in the global numbering DD[1..20] (INT(topoN, n1, ..., n12)). Momenta as in FORM: p1, p2,\n"
                "   r1, k1, k2 incoming, q = -p1-p2-r1; k1 = amplitude loop, k2 = conjugate loop (-i0); DD[20] = (k1+k2)^2\n"
                "   is an irreducible numerator. Den[k] = 1/k^2, Den[k, m2] = 1/(k^2 - m2), DD[3] = 1/(-q.p1 + u q.p2). *)\n{\n{\n")
        f.write(",\n".join(" {" + ", ".join(f"DD[{d}]" for d in [1, 2, 3] + box[a] + [d + SHIFT2 for d in box[b]] + [20])
                           + "}" for a, b in fams) + "\n},\n{\n")
        defs = [" DD[1] -> Den[r1]", " DD[2] -> Den[p1+p2+r1, m2]", " DD[3] -> Den[-sp[q, p1] + u*sp[q, p2]]"]
        defs += [f" DD[{d}] -> Den[{momk[d]}]" for d in sorted(momk)]
        f.write(",\n".join(defs) + "\n}\n}\n")
    with open(os.path.join(HERE, "rvv_topsectors.m"), "w") as f:
        f.write("(* generated by Families/rvv_families.py: top sectors (sector ID over the 12 positions, t): all 11\n"
                "   propagators (cuts + both boxes); position 12 = (k1+k2)^2 is a numerator only *)\n{\n")
        f.write(",\n".join(f" {{topo{n}, {{{{{2 ** 11 - 1}, 11}}}}}}" for n in range(1, len(fams) + 1)) + "\n}\n")
    print(f"{len(fams)} families -> fams/rvv_*.inc, rvv_families.txt, integralfamilies_r.rvv.m, rvv_topsectors.m")


if __name__ == "__main__":
    main()
